  function search(q) {
    const nq = norm(q); if (!nq) return [];
    const words = nq.split(' ');
    const scored = G.map(d => {
      const names = [d.name, ...(d.syn || [])].map(norm);
      const tests = [...(d.first || []), ...(d.then || []), ...(d.also || [])].map(x => norm(x.name)).join(' | ');
      let s = 0;
      if (names.some(n => n === nq)) s = 100;
      else if (names.some(n => n.startsWith(nq))) s = 80;
      else if (names.some(n => (' ' + n + ' ').includes(' ' + nq))) s = 70;
      else if (names.some(n => n.includes(nq))) s = 60;
      else if (words.every(w => names.some(n => n.includes(w)))) s = 50;
      else if (nq.length >= 2 && (' ' + tests + ' ').includes(' ' + nq)) s = 30; // typed a test name: diseases that use it
      else if (words.every(w => tests.includes(w)) && nq.length >= 3) s = 20;
      return { d, s };
    }).filter(x => x.s > 0).sort((a, b) => b.s - a.s || a.d.name.localeCompare(b.d.name));
    return scored;
  }
