/* node tests/test_hahabx.js - Hospital at Home antibiotic rules */
const H = require("../tools/hahabx/rules.js");
let fail = 0;
const ok = (n, c, x) => { if (!c) fail++; console.log((c ? "ok   " : "FAIL ") + n + (!c && x !== undefined ? " | " + JSON.stringify(x).slice(0, 300) : "")); };
const j = (name, text, route, lim) => H.judge({ name, text, route: route || "IV" }, lim);
ok("q8h = 3/day", H.perDay("1 g IV q8h").perDay === 3);
ok("q6h = 4/day", H.perDay("every 6 hours").perDay === 4);
ok("BID = 2/day", H.perDay("twice daily").perDay === 2);
ok("FHIR timing 1 per 8 h = 3/day", H.perDay("", { repeat: { frequency: 1, period: 8, periodUnit: "h" } }).perDay === 3);
ok("continuous infusion read", H.perDay("12 g over 24 h continuous").cont);
ok("ceftriaxone q24h: nurse bolus OK", j("ceftriaxone", "2 g IV q24h").level === "ok");
ok("vancomycin q12h: nurse bolus OK at limit 2", j("vancomycin", "1 g IV q12h").level === "ok");
ok("pip-tazo q6h: elastomeric", j("piperacillin-tazobactam", "4.5 g IV q6h").level === "elasto");
ok("cloxacillin q4h: elastomeric 8-12 g", /8–12 g/.test(j("cloxacillin", "2 g IV q4h").detail));
ok("cefazolin q8h: elastomeric at limit 2 (more than BID)", j("cefazolin", "2 g IV q8h").level === "elasto");
ok("cefazolin q8h: bolus OK when TID visits allowed", j("cefazolin", "2 g IV q8h", "IV", 3).level === "ok");
const mero = j("meropenem", "1 g IV q8h");
ok("meropenem q8h: elastomeric per pharmacy, ertapenem offered", mero.level === "pharm" && mero.alts.some((a) => a.d.key === "erta"), mero);
const imi = j("imipenem", "500 mg IV q6h");
ok("imipenem: not possible at home", imi.level === "bad");
ok("ampicillin q6h: not possible, alternatives given", j("ampicillin", "2 g IV q6h").level === "bad");
ok("metronidazole PO: oral", j("metronidazole", "500 mg PO BID", "PO").level === "ok");
ok("frequency missing: unknown", j("piperacillin-tazobactam", "4.5 g IV").level === "unk");
ok("already continuous pip-tazo: OK", j("piperacillin-tazobactam", "13.5 g IV continuous over 24 h").level === "ok");
let o = H.options("esbl");
ok("ESBL: ertapenem first, imipenem never", o[0].d.key === "erta" && !o.some((r) => r.d.key === "imi"), o.map((r) => r.d.key));
o = H.options("pseudo");
ok("Pseudomonas: pip-tazo and ceftazidime elastomeric, meropenem per pharmacy", ["piptazo", "ceftaz", "mero"].every((k) => o.some((r) => r.d.key === k)), o.map((r) => r.d.key));
o = H.options("mssa");
ok("MSSA: cefazolin + probenecid q24h before cloxacillin elastomeric", o.findIndex((r) => r.d.key === "cefaz" && r.how === "Nurse bolus") < o.findIndex((r) => r.d.key === "clox"), o.map((r) => r.d.key + ":" + r.how));
ok("MRSA: vancomycin and daptomycin", ["vanco", "dapto"].every((k) => H.options("mrsa").some((r) => r.d.key === k)));
ok("every scenario has an option", H.SCEN.every(([k]) => H.options(k).length), H.SCEN.filter(([k]) => !H.options(k).length));
ok("antibiotic name filter: not acetaminophen", !H.ABX_RE.test("acetaminophen") && H.ABX_RE.test("cefazolin"));
ok("daptomycin q8h: once-daily regimen highlighted", j("daptomycin", "IV q8h").daily.length === 1);
ok("cefazolin: once daily with probenecid; pip-tazo: none", /probenecid/.test(j("cefazolin", "2 g IV q8h").daily[0]) && !j("piperacillin-tazobactam", "4.5 g IV q6h").daily.length);
ok("ESBL options: ertapenem marked once daily", H.options("esbl")[0].once);
console.log(fail ? `\n${fail} FAILED` : "\nall passed"); process.exit(fail ? 1 : 0);
