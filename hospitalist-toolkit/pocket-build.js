// Writes pocket-files.js: the list of files the iPhone pocket app saves for offline use (pocket-sw.js).
// Run after changing any tool:  node pocket-build.js   (from hospitalist-toolkit/)
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const SKIP = /^(tests|node_modules|build)(\/|$)|(^|\/)(test-pdfs|__pycache__)(\/|$)|\.(py|md|map|txt)$|^pocket-files\.js$|^pocket-build\.js$/;
const files = [], hash = crypto.createHash("sha1");
(function walk(dir) {
  for (const n of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, n), rel = path.relative(__dirname, full).split(path.sep).join("/");
    if (n.startsWith(".") || SKIP.test(rel)) continue;
    if (fs.statSync(full).isDirectory()) walk(full);
    else { files.push(rel); hash.update(rel); hash.update(fs.readFileSync(full)); }
  }
})(__dirname);
const CDN = [
  "https://cdn.jsdelivr.net/npm/fhirclient@2.5.2/build/fhir-client.js",
  "https://cdn.jsdelivr.net/npm/fhirclient/build/fhir-client.js",
  "https://cdn.jsdelivr.net/npm/pdf-lib@1.17.1/dist/pdf-lib.min.js",
  "https://cdn.jsdelivr.net/npm/pdfjs-dist@3.11.174/build/pdf.min.js",
  "https://cdn.jsdelivr.net/npm/pdfjs-dist@3.11.174/build/pdf.worker.min.js",
];
const version = hash.digest("hex").slice(0, 10);
fs.writeFileSync(path.join(__dirname, "pocket-files.js"),
  "// Generated by pocket-build.js - do not edit. Files saved for offline use by the iPhone pocket app.\n" +
  "self.POCKET_VERSION = " + JSON.stringify(version) + ";\n" +
  "self.POCKET_FILES = " + JSON.stringify(["index.html?pocket=1"].concat(files, CDN), null, 0).replace(/","/g, '",\n"') + ";\n");
console.log("pocket-files.js:", files.length, "files + CDN, version", version);
